-- Portfolio 1: Ride-Hailing Trip and Payment Records
-- Relational schema for PostgreSQL (tested on 16.x; uses nothing newer).
-- Run against an empty database:  psql -d ridehailing -f 01_schema.sql

BEGIN;

DROP TABLE IF EXISTS payment CASCADE;
DROP TABLE IF EXISTS trip    CASCADE;
DROP TABLE IF EXISTS driver  CASCADE;
DROP TABLE IF EXISTS rider   CASCADE;
DROP FUNCTION IF EXISTS check_payment_trip() CASCADE;

-- A rider requests trips. Phone is the login identity, so it must be unique.
CREATE TABLE rider (
    rider_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   varchar(100) NOT NULL,
    phone       varchar(16)  NOT NULL,
    email       varchar(120),
    created_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_rider_phone  UNIQUE (phone),
    CONSTRAINT uq_rider_email  UNIQUE (email),
    CONSTRAINT chk_rider_name  CHECK (length(btrim(full_name)) > 0),
    CONSTRAINT chk_rider_phone CHECK (phone ~ '^\+?[0-9]{7,15}$'),
    CONSTRAINT chk_rider_email CHECK (email IS NULL OR email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$')
);

-- A driver owns one registered vehicle. Licence and plate cannot be shared.
CREATE TABLE driver (
    driver_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     varchar(100) NOT NULL,
    phone         varchar(16)  NOT NULL,
    licence_no    varchar(20)  NOT NULL,
    vehicle_plate varchar(12)  NOT NULL,
    vehicle_type  varchar(10)  NOT NULL,
    rating        numeric(2,1),
    is_available  boolean      NOT NULL DEFAULT true,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_driver_phone   UNIQUE (phone),
    CONSTRAINT uq_driver_licence UNIQUE (licence_no),
    CONSTRAINT uq_driver_plate   UNIQUE (vehicle_plate),
    CONSTRAINT chk_driver_name   CHECK (length(btrim(full_name)) > 0),
    CONSTRAINT chk_driver_phone  CHECK (phone ~ '^\+?[0-9]{7,15}$'),
    CONSTRAINT chk_driver_vtype  CHECK (vehicle_type IN ('sedan', 'suv', 'minivan', 'motorbike')),
    CONSTRAINT chk_driver_rating CHECK (rating IS NULL OR rating BETWEEN 1.0 AND 5.0)
);

-- A trip moves through: requested -> assigned -> in_progress -> completed.
-- It can be cancelled before it starts. The checks below tie each status
-- to the fields that must (or must not) be filled at that point.
CREATE TABLE trip (
    trip_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rider_id      integer      NOT NULL REFERENCES rider (rider_id)  ON DELETE RESTRICT,
    driver_id     integer               REFERENCES driver (driver_id) ON DELETE RESTRICT,
    pickup_zone   varchar(40)  NOT NULL,
    dropoff_zone  varchar(40)  NOT NULL,
    status        varchar(12)  NOT NULL DEFAULT 'requested',
    requested_at  timestamptz  NOT NULL DEFAULT now(),
    started_at    timestamptz,
    completed_at  timestamptz,
    distance_km   numeric(6,2),
    fare_amount   numeric(10,2),
    CONSTRAINT chk_trip_status
        CHECK (status IN ('requested', 'assigned', 'in_progress', 'completed', 'cancelled')),
    -- a request waiting for a match has no driver yet
    CONSTRAINT chk_trip_requested_no_driver
        CHECK (status <> 'requested' OR driver_id IS NULL),
    -- once assigned, started or completed, a driver must be recorded
    CONSTRAINT chk_trip_driver_required
        CHECK (status NOT IN ('assigned', 'in_progress', 'completed') OR driver_id IS NOT NULL),
    CONSTRAINT chk_trip_started
        CHECK (status NOT IN ('in_progress', 'completed') OR started_at IS NOT NULL),
    CONSTRAINT chk_trip_completed
        CHECK (status <> 'completed' OR (completed_at IS NOT NULL AND fare_amount IS NOT NULL AND distance_km IS NOT NULL)),
    CONSTRAINT chk_trip_time_order
        CHECK ((started_at IS NULL OR started_at >= requested_at)
           AND (completed_at IS NULL OR (started_at IS NOT NULL AND completed_at >= started_at))),
    CONSTRAINT chk_trip_distance CHECK (distance_km IS NULL OR distance_km > 0),
    CONSTRAINT chk_trip_fare     CHECK (fare_amount IS NULL OR fare_amount >= 0)
);

-- One driver, one active trip. A plain UNIQUE on driver_id would block a
-- driver's trip history, so the rule only covers the two active statuses.
CREATE UNIQUE INDEX uq_trip_driver_active
    ON trip (driver_id)
    WHERE status IN ('assigned', 'in_progress');

-- Foreign keys are not indexed automatically in PostgreSQL.
CREATE INDEX ix_trip_rider  ON trip (rider_id);
CREATE INDEX ix_trip_driver ON trip (driver_id);

-- One payment record per trip. Amounts are in Naira by default.
CREATE TABLE payment (
    payment_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id     integer       NOT NULL REFERENCES trip (trip_id) ON DELETE RESTRICT,
    amount      numeric(10,2) NOT NULL,
    currency    char(3)       NOT NULL DEFAULT 'NGN',
    method      varchar(10)   NOT NULL,
    status      varchar(10)   NOT NULL DEFAULT 'pending',
    reference   varchar(40)   NOT NULL,
    paid_at     timestamptz,
    CONSTRAINT uq_payment_trip      UNIQUE (trip_id),
    CONSTRAINT uq_payment_reference UNIQUE (reference),
    CONSTRAINT chk_payment_amount   CHECK (amount > 0),
    CONSTRAINT chk_payment_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT chk_payment_method   CHECK (method IN ('card', 'cash', 'wallet')),
    CONSTRAINT chk_payment_status   CHECK (status IN ('pending', 'succeeded', 'failed', 'refunded')),
    CONSTRAINT chk_payment_paid_at  CHECK (status NOT IN ('succeeded', 'refunded') OR paid_at IS NOT NULL)
);

-- A CHECK constraint cannot look at another table, so this rule needs a
-- trigger: a payment can only be recorded for a completed trip, and the
-- amount must match the fare on that trip.
CREATE FUNCTION check_payment_trip() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_status trip.status%TYPE;
    v_fare   trip.fare_amount%TYPE;
BEGIN
    SELECT status, fare_amount INTO v_status, v_fare
    FROM trip WHERE trip_id = NEW.trip_id;

    IF NOT FOUND THEN
        RETURN NULL;  -- the foreign key reports the missing trip
    END IF;
    IF v_status <> 'completed' THEN
        RAISE EXCEPTION 'payment rejected: trip % has status %, expected completed', NEW.trip_id, v_status
            USING ERRCODE = 'check_violation', CONSTRAINT = 'payment_requires_completed_trip';
    END IF;
    IF NEW.amount <> v_fare THEN
        RAISE EXCEPTION 'payment rejected: amount % does not match trip fare %', NEW.amount, v_fare
            USING ERRCODE = 'check_violation', CONSTRAINT = 'payment_matches_trip_fare';
    END IF;
    RETURN NULL;  -- return value is ignored for AFTER triggers
END;
$$;

-- AFTER, so the column CHECKs, NOT NULLs and keys report their own errors
-- first and this trigger only judges otherwise well-formed rows.
CREATE TRIGGER trg_payment_trip
    AFTER INSERT OR UPDATE OF trip_id, amount ON payment
    FOR EACH ROW EXECUTE FUNCTION check_payment_trip();

COMMIT;
